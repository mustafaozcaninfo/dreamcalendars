"use strict";
const selectA = document.getElementById("budget-a");
const selectB = document.getElementById("budget-b");
let scenarios;

function updatePlan() {
  if (!scenarios) return;
  const current = scenarios[`${selectA.value}-${selectB.value}`];
  const summary = current.summary;
  document.getElementById("covered").textContent = summary.covered_by_suggested_pto_child_hours;
  document.getElementById("remaining").textContent = summary.remaining_gap_child_hours;
  document.querySelector(".gap-metric").classList.toggle("needs-care", summary.remaining_gap_child_hours > 0);
  for (const day of ["16", "20"]) {
    const row = current.days.find(item => item.date === `2026-10-${day}`);
    const names = row.suggested_pto.map(id => id === "parent-a" ? "Parent A" : "Parent B");
    document.getElementById(`suggestion-${day}`).textContent = names.length
      ? `Suggested: ${names.join(" and ")} takes this day off.`
      : "No available leave can cover this gap in the example.";
    document.getElementById(`gap-${day}`).textContent = `With suggested leave: ${row.remaining_gap_child_hours} child-hours remain.`;
  }
}

// These synthetic scenarios were generated by the tested Python planner.
// This browser preview never fetches user data or calls a model API.
selectA.disabled = true;
selectB.disabled = true;
fetch("demo/scenarios.json")
  .then(response => {
    if (!response.ok) throw new Error("Scenario file unavailable");
    return response.json();
  })
  .then(data => {
    scenarios = data.scenarios;
    selectA.disabled = false;
    selectB.disabled = false;
    updatePlan();
  })
  .catch(() => {
    document.getElementById("demo-error").hidden = false;
  });
selectA.addEventListener("change", updatePlan);
selectB.addEventListener("change", updatePlan);
document.getElementById("print-corrections").addEventListener("click", () => window.print());
