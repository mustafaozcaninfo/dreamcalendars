<p>The answer of <em>how many weeks in a year</em> seems to be obvious because it is related to elementary mathematics. You can count them by dividing 365 days per year by seven days per week. This way we&rsquo;ll get 52 weeks plus one day. If it is one of the leap years with 366 days, it has 52 weeks plus two extra days. In other words, one can say that a regular year contains 52 1/7 weeks and a leap year consists of 52 2/7 weeks. Leap year is a year that occurs once every 4 years. It consists of 366 days, and the intercalary day is always the 29th of February.</p>
