<h2><strong>Astronomy and Mathematics</strong></h2>
<p>A week is a period of seven days. Most years have 365 days, but a leap year has 366 days. That adds up to 52 weeks (where each week is exactly 7 days) plus 1 or 2 additional days. For example, the year 2019 has exactly 365 days. Now if the year starts on a week in a non-leap year, you end up with 53 weeks. Or if either of the first two days lands on a week during a leap year, then you can also get 53 weeks. Consider astronomy, the sun and earth&rsquo;s distance between each other is 149.59787 million kilometers, in other words, it&rsquo;s 93 million miles away. If we count days in the year, the exact amount of days would be 365.256363004 days, equivalent to a full year. Before the sun returns back to the meridian the earth must rotate fully around the sun in which we call, the solar day that takes on average 24 hours. We experience a leap year for every four years that past which includes an extra day on our calendar, that particularly is responsible for the extra 4 weeks that gives us approximately 52.29 weeks during this transition.</p>
