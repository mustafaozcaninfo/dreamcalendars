<h2><strong>Grandparents&rsquo; Day Background</strong></h2>
<p>Celebrated in the United States since 1978, the United States Senate and <a href="https://en.wikipedia.org/wiki/Jimmy_Carter" target="_blank" rel="noopener nofollow">President Jimmy Carter</a> nationally recognized Marian McQuade of Oak Hill, West Virginia as the founder of National Grandparents&rsquo; Day.&nbsp; Grandparents&rsquo; Day is a holiday created by federal proclamation in 1978. It was passed by Congress and signed into law by President Jimmy Carter. It is a "real" holiday. It is not, however, one of the federal holidays for which government workers receive a day off. Marian McQuade, a West Virginia mother of 15, began a campaign for Grandparents&rsquo; Day in 1970. Three years later, her home state created the first Grandparents&rsquo; Day in the nation. The movement for a national holiday stalled, however. McQuade and her supporters rallied the media and urged organizations for older Americans to support the cause. They finally succeeded eight years later. McQuade died in 2008. When she died, she had 43 grandchildren and 15 great-grandchildren.</p>
<p>Only a few other countries have official Grandparents&rsquo; Day holidays.</p>
